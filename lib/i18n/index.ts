// bahasa aktif; fallback ke "id" hanya bila lang invalid (runtime/localStorage).

export const LANG_STORAGE_KEY = "eps_lang";
export const DEFAULT_LANG: Lang = "id";

export const LANGS = [
  { code: "id", label: "Indonesia", flag: "🇮🇩" },
  { code: "en", label: "English", flag: "🇬🇧" },
  { code: "zh", label: "中文", flag: "🇨🇳" },
  { code: "ko", label: "한국어", flag: "🇰🇷" },
  { code: "ja", label: "日本語", flag: "🇯🇵" },
] as const satisfies readonly { code: string; label: string; flag: string }[];

export type Lang = "id" | "en" | "zh" | "ko" | "ja";

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && LANGS.some((l) => l.code === value);
}

export function loadLang(storage: Pick<Storage, "getItem"> | null = null): Lang {
  if (!storage) return DEFAULT_LANG;
  try {
    const raw = storage.getItem(LANG_STORAGE_KEY);
    return isLang(raw) ? raw : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function saveLang(lang: Lang, storage: Pick<Storage, "setItem"> | null = null): void {
  if (!storage) return;
  storage.setItem(LANG_STORAGE_KEY, lang);
}

